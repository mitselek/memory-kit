#!/usr/bin/env python3
"""Generate memory/lessons/index.yaml from the lesson files' front matter.

Each memory/lessons/<slug>.md starts with a YAML front-matter block carrying the index fields
(memory-kit/types/memory-lessons.ts) except `slug`, which is the file name:

    ---
    summary: "What it is for, not what it says."
    learned: "2026-10-13"
    ref: mihkel:2026-10-13
    enforcement: recognition        # hooked | linted | recognition
    trigger: ""                     # only when hooked
    ---
    # Title
    When -- Why -- What to do -- What not to do.

Usage: tools/lesson-index.py [memory_dir]          write the index (default: the memory_dir of the
                                           nearest memory-kit.conf, else memory)
       tools/lesson-index.py [memory_dir] --from-index  one-time upgrade: write front matter into
                                           lessons that lack it, from the existing index
       tools/lesson-index.py [memory_dir] --check  exit 1 if the index on disk is not what would be generated
       tools/lesson-index.py --help | -h           print this usage and write nothing

A key given twice, in a lesson's front matter or in the index, stops the run, naming the file, the
key and both lines as the lint does; plain YAML would keep the last copy, silently (kit #55).
"""
import sys
from pathlib import Path

import yaml

# Importing strict_yaml must leave no lint/__pycache__ in a home's vendored kit: an untracked file
# there is a dirty tree, which kit-update.py refuses.
sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "lint"))
import kit_home  # noqa: E402  (kit #62: memory-kit.conf names the memory directory)
# A key given twice is an error, as the lint reads it, never the last copy kept silently (kit #55).
from strict_yaml import DuplicateKey, strict_load  # noqa: E402

FIELDS = ("summary", "learned", "ref", "enforcement", "trigger")


def write(path, text):
    """UTF-8 with LF on every platform. Not Path.write_text, whose newline= is Python 3.10+, and
    macOS's system python3 is 3.9 (kit #34)."""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def front_matter(path):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        sys.exit(f"{path}: no front matter")
    head, sep, _ = text[4:].partition("\n---\n")
    if not sep:
        sys.exit(f"{path}: front matter not closed")
    try:
        meta = strict_load(head) or {}
    except DuplicateKey as e:
        # Lines counted in the whole file, as the lint counts them: the front matter starts on line 2.
        sys.exit(f"{path}: front matter: {e.shifted(1).message()}")
    unknown = set(meta) - set(FIELDS)
    if unknown:
        sys.exit(f"{path}: unknown front-matter key(s) {', '.join(sorted(unknown))}")
    return meta


def generate(lessons_dir):
    rows = []
    for p in sorted(lessons_dir.glob("*.md")):
        if p.stem == "README":
            continue
        meta = front_matter(p)
        row = {"slug": p.stem}
        for k in FIELDS:
            v = meta.get(k)
            if k == "trigger" and not v:
                continue
            row[k] = str(v) if k == "learned" else ("" if v is None else v)
        rows.append(row)
    header = ("# GENERATED by memory-kit/tools/lesson-index.py from the lesson files' front matter.\n"
              "# Never hand-edit; edit the lesson and regenerate.\n\n")
    return header + yaml.safe_dump({"lessons": rows}, allow_unicode=True, sort_keys=False, width=200)


def index_rows(index):
    """The rows of the index on disk; a key given twice stops the run (kit #55)."""
    try:
        return (strict_load(index.read_text(encoding="utf-8")) or {}).get("lessons")
    except DuplicateKey as e:
        sys.exit(f"{index}: {e.message()}")


def from_index(lessons_dir, index):
    rows = index_rows(index) or []
    done = 0
    for r in rows:
        p = lessons_dir / f"{r['slug']}.md"
        if not p.exists() or p.read_text(encoding="utf-8").startswith("---\n"):
            continue
        meta = {k: r[k] for k in FIELDS if r.get(k) not in (None, "")}
        head = yaml.safe_dump(meta, allow_unicode=True, sort_keys=False, width=200)
        write(p, "---\n" + head + "---\n" + p.read_text(encoding="utf-8"))
        done += 1
    print(f"{index}: front matter written into {done} lesson(s)")


def usage():
    return __doc__[__doc__.index("Usage:"):].split("\n\n")[0]


def default_memory_dir():
    """No folder named: the memory_dir of the nearest memory-kit.conf, as the other tools read it."""
    found = kit_home.resolve(Path.cwd(), upward=True)
    if found.problem:
        sys.exit(f"memory-kit: {found.problem}")
    name = "memory"
    conf = found.home / "memory-kit.conf"
    if conf.exists():
        try:
            name = (strict_load(conf.read_text(encoding="utf-8")) or {}).get("memory_dir", "memory")
        except DuplicateKey as e:
            sys.exit(f"memory-kit: {conf}: {e.message()}")
    return found.home / name


def main(argv):
    if "--help" in argv or "-h" in argv:
        print(usage())
        return 0
    flags = [a for a in argv if a.startswith("-")]
    unknown = [a for a in flags if a not in ("--from-index", "--check")]
    if unknown:
        sys.stderr.write(f"lesson-index.py: unknown option {unknown[0]}\n{usage()}\n")
        return 2
    args = [a for a in argv if not a.startswith("-")]
    mem = Path(args[0]) if args else default_memory_dir()
    if not mem.is_dir():
        sys.stderr.write(f"lesson-index.py: no such memory directory: {mem}\n")
        return 1
    lessons = mem / "lessons"
    index = lessons / "index.yaml"
    if "--check" in argv or "--from-index" in argv:
        if not lessons.is_dir():
            sys.stderr.write(f"lesson-index.py: no such lessons directory: {lessons}\n")
            return 1
    else:
        lessons.mkdir(exist_ok=True)
    if "--from-index" in argv:
        from_index(lessons, index)
        return 0
    want = generate(lessons)
    if "--check" in argv:
        have = index_rows(index) if index.exists() else None
        if have != yaml.safe_load(want)["lessons"]:
            print(f"{index}: stale -- run memory-kit/tools/lesson-index.py")
            return 1
        return 0
    write(index, want)
    print(f"{index}: {want.count('- slug:')} lessons")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
